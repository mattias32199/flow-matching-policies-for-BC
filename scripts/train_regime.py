"""State FBC under different demonstration-data regimes (block-double data/compute study).

Data comes from the shared collection store (scripts/collections_store.py, 1K expert episodes each,
successful episodes only). The training buffer is a FIFO window of collections:
  fixed N        --base N                         collections 0..N/1K-1, never refreshed
  replay         --base N --refresh-every R       every R updates add --refresh-collections new
                                                  collections (indices 1000+) and evict the oldest
  start interval --start-interval k               only chunk starts at episode steps 0, k, 2k, ...
                                                  (= frames a visual policy would have rendered)
Same model / optimizer / evaluation as scripts/train.py. Requeue-safe: SIGTERM/SIGUSR1 saves
runs/<run>/ckpt.pkl + state.json and exits 143; a restart resumes from them. Refresh collections
are generated by a background subprocess into runs/<run>/stream/ and deleted when evicted.

  python scripts/train_regime.py --run r-fixed-n30k --base 30000 --steps 1000000
"""
import argparse
import json
import os
import pickle
import signal
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
sys.path.insert(0, str(ROOT / 'ocbench' / 'impls'))

import flax  # noqa: E402
import jax  # noqa: E402
import numpy as np  # noqa: E402
from agents.fbc import FBCAgent, get_config  # noqa: E402
from envs.env_utils import ActionNormalizer  # noqa: E402
from utils.evaluation_mjwarp import evaluate_mjwarp  # noqa: E402

import collections_store as cs  # noqa: E402
from train import EvalAgent, Features, dataset, emit, evaluation_record, save_preprocessing, saved_preprocessing  # noqa: E402

REFRESH_BASE = 1000
STOP = {'flag': False}


def on_signal(signum, frame):
    STOP['flag'] = True


def allowed_starts(train, k):
    if k <= 1:
        return None
    idx = np.arange(train.size)
    return idx[(idx - train.episode_offsets[np.searchsorted(train.terminal_locs, idx)]) % k == 0]


class Window:
    """FIFO buffer of collections; refresh collections come from a background generator."""

    def __init__(self, args, run, window):
        self.args, self.run, self.window = args, run, list(window)
        self.stream = run / 'stream'
        self.stream.mkdir(exist_ok=True)
        self.procs = {}
        self.parts = {}

    def file(self, idx):
        return cs.path(self.args.env, self.args.data_seed, idx) if idx < REFRESH_BASE else self.stream / f'c{idx:05d}.npz'

    def prefetch(self, idxs):
        for i in idxs:
            if i < REFRESH_BASE or self.file(i).exists() or i in self.procs:
                continue
            self.procs[i] = subprocess.Popen(
                [sys.executable, str(ROOT / 'scripts' / 'collections_store.py'), '--env', self.args.env,
                 '--seed', str(self.args.data_seed), '--idx', str(i), '--out-dir', str(self.stream)],
                stdout=open(self.stream / f'gen{i}.log', 'w'), stderr=subprocess.STDOUT)

    def wait(self, i):
        f = self.file(i)
        if i < REFRESH_BASE:
            if not f.exists():  # store should be prefilled; generate in-process as a fallback
                cs.ensure(self.args.env, self.args.data_seed, i)
            return f
        self.prefetch([i])
        if i in self.procs:
            code = self.procs.pop(i).wait()
            if code != 0 or not f.exists():
                raise RuntimeError(f'collection {i} generation failed ({code}), see {self.stream}/gen{i}.log')
        return f

    def build(self, normalizer=None):
        keep_parts = self.args.refresh_every > 0
        for i in self.window:
            if i not in self.parts:
                self.parts[i] = cs.load([self.wait(i)])
        for i in list(self.parts):
            if i not in self.window:
                del self.parts[i]
                if i >= REFRESH_BASE:
                    self.file(i).unlink(missing_ok=True)
        raw = cs.load_parts([self.parts[i] for i in self.window], keep=keep_parts)
        if not keep_parts:
            self.parts = {}
        raw.pop('qpos', None)
        if normalizer is None:
            normalizer = ActionNormalizer.fit(raw['actions'], 1., 5.)
        return raw, normalizer


def save(run, agent, state):
    tmp = run / 'ckpt.pkl.tmp'
    with open(tmp, 'wb') as f:
        pickle.dump(dict(agent=flax.serialization.to_state_dict(agent)), f)
    tmp.replace(run / 'ckpt.pkl')
    (run / 'state.json.tmp').write_text(json.dumps(state))
    (run / 'state.json.tmp').replace(run / 'state.json')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--env', default='block-double-task1-v0')
    p.add_argument('--features', default='handcrafted', help='see train.Features (e.g. standardized+ego+pair)')
    p.add_argument('--seed', type=int, default=0)
    p.add_argument('--data-seed', type=int, default=0)
    p.add_argument('--base', type=int, default=10000, help='episodes in the buffer (multiple of 1000)')
    p.add_argument('--refresh-every', type=int, default=0, help='updates between refreshes; 0 = fixed data')
    p.add_argument('--refresh-collections', type=int, default=1)
    p.add_argument('--start-interval', type=int, default=1)
    p.add_argument('--steps', type=int, default=1000000)
    p.add_argument('--batch-size', type=int, default=1024)
    p.add_argument('--width', type=int, default=4096)
    p.add_argument('--depth', type=int, default=8)
    p.add_argument('--log-interval', type=int, default=1000)
    p.add_argument('--eval-interval', type=int, default=50000)
    p.add_argument('--eval-episodes', type=int, default=500)
    p.add_argument('--save-interval', type=int, default=25000)
    p.add_argument('--group', default='double-data-regime')
    p.add_argument('--tags', default='')
    p.add_argument('--run', required=True)
    args = p.parse_args()
    from simulation import configure_iteration_warnings
    configure_iteration_warnings(False)
    signal.signal(signal.SIGTERM, on_signal)
    signal.signal(signal.SIGUSR1, on_signal)
    run = ROOT / 'runs' / args.run
    run.mkdir(parents=True, exist_ok=True)
    if (run / 'DONE').exists():
        print('already done', flush=True)
        return
    n_base = args.base // 1000
    resume = json.loads((run / 'state.json').read_text()) if (run / 'state.json').exists() and (run / 'ckpt.pkl').exists() else None
    config = vars(args) | dict(trainer='train_regime', tags=[t for t in args.tags.split(',') if t],
                               wandb_group=args.group, slurm_job=os.environ.get('SLURM_JOB_ID'))
    if not resume:
        (run / 'config.json').write_text(json.dumps(config, indent=2))
    print(f'JAX_DEVICES {jax.devices()}', flush=True)
    start = time.monotonic()
    win = Window(args, run, resume['window'] if resume else range(n_base))
    refreshes = resume['refreshes'] if resume else 0

    def next_ids(j):  # collections added by refresh number j (1-based)
        k = args.refresh_collections
        return list(range(REFRESH_BASE + (j - 1) * k, REFRESH_BASE + j * k))

    if args.refresh_every:
        win.prefetch(next_ids(refreshes + 1) + next_ids(refreshes + 2))
    if resume:
        features, normalizer = saved_preprocessing(run / 'preprocessing.npz', args.features)
        raw, _ = win.build(normalizer)
    else:
        raw, normalizer = win.build()
    train = dataset(raw, normalizer)
    del raw
    raw_val = cs.load([cs.ensure(args.env, args.data_seed, 'val')])
    raw_val.pop('qpos', None)
    val = dataset(raw_val, normalizer)
    del raw_val
    if not resume:
        features = Features(train['observations'], args.features)
        save_preprocessing(run / 'preprocessing.npz', features, normalizer)
    allowed = allowed_starts(train, args.start_interval)

    def data_record(step):
        return dict(step=step, refreshes=refreshes, window=[min(win.window), max(win.window)],
                    buffer_episodes=int(train['terminals'].sum()), buffer_transitions=int(train.size),
                    allowed_starts=int(train.size if allowed is None else len(allowed)),
                    collections_seen=n_base + refreshes * args.refresh_collections,
                    seconds=round(time.monotonic() - start, 1))

    emit(run / 'data.jsonl', data_record(resume['step'] if resume else 0))
    cfg = get_config()
    cfg.actor_hidden_dims = (args.width,) * args.depth
    cfg.batch_size = args.batch_size
    ex = train.sample(1, keys=('observations', 'actions'))
    agent = FBCAgent.create(args.seed, features(ex['observations']), ex['actions'], cfg)
    first = 1
    if resume:
        with open(run / 'ckpt.pkl', 'rb') as f:
            agent = flax.serialization.from_state_dict(agent, pickle.load(f)['agent'])
        first = resume['step'] + 1
        emit(run / 'resume.jsonl', dict(step=resume['step'], job=os.environ.get('SLURM_JOB_ID'), time=time.time()))
    sampler = np.random.default_rng([args.seed, first])
    diagnostic = np.random.default_rng([args.seed + 10000, first])

    def state(step):
        return dict(step=step, window=win.window, refreshes=refreshes)

    for step in range(first, args.steps + 1):
        if args.refresh_every and step % args.refresh_every == 0:
            refreshes += 1
            win.window = (win.window + next_ids(refreshes))[-n_base:]
            del train
            raw, _ = win.build(normalizer)
            train = dataset(raw, normalizer)
            del raw
            allowed = allowed_starts(train, args.start_interval)
            win.prefetch(next_ids(refreshes + 1) + next_ids(refreshes + 2))
            emit(run / 'data.jsonl', data_record(step))
        idxs = sampler.integers(train.size, size=args.batch_size) if allowed is None else allowed[sampler.integers(len(allowed), size=args.batch_size)]
        batch = train.sample(args.batch_size, idxs=idxs, keys=('observations', 'actions'))
        batch['observations'] = features(batch['observations'])
        agent, info = agent.update(batch)
        if step == first or step % args.log_interval == 0:
            loss = float(info['actor/actor_loss'])
            if not np.isfinite(loss):
                raise RuntimeError(f'Nonfinite loss at step {step}')
            rec = {'step': step, 'seconds': time.monotonic() - start, 'training/flow_loss': loss,
                   'data/collections_seen': n_base + refreshes * args.refresh_collections}
            for name, source in [('training', train), ('validation', val)]:
                ids = diagnostic.integers(source.size, size=args.batch_size)
                mb = source.sample(args.batch_size, idxs=ids, keys=('observations', 'actions'))
                mb['observations'] = features(mb['observations'])
                rng = jax.random.PRNGKey(int(diagnostic.integers(2**31)))
                _, flow_info = agent.total_loss(mb, grad_params=None, rng=rng)
                rec[f'{name}/flow_loss'] = float(flow_info['actor/actor_loss'])
                rec[f'{name}/action_mse'] = float(agent.compute_metrics(mb, rng=rng)['actor/mse'])
            emit(run / 'metrics.jsonl', rec)
        if step % args.eval_interval == 0 or step == args.steps:
            np.random.seed(args.seed * 100000 + step)
            metrics, _, _ = evaluate_mjwarp(EvalAgent(agent, features), args.env, config=agent.config,
                                            action_normalizer=normalizer, num_eval_episodes=args.eval_episodes,
                                            action_chunk_length=25)
            emit(run / 'eval.jsonl', evaluation_record(step, metrics))
        if step % args.save_interval == 0 or step == args.steps or STOP['flag']:
            save(run, agent, state(step))
            if STOP['flag'] and step != args.steps:
                print(f'signal: checkpointed at {step}, exiting for requeue', flush=True)
                for pr in win.procs.values():
                    pr.terminate()
                sys.exit(143)
    (run / 'DONE').write_text('ok\n')
    for pr in win.procs.values():
        pr.terminate()
        pr.wait()
    for f in win.stream.glob('c*.npz'):
        f.unlink()


if __name__ == '__main__':
    main()
