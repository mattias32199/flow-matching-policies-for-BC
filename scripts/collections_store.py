"""Shared on-disk store of expert demonstration collections (1K episodes each) for data-regime sweeps.

Collection i of (env, data_seed) is generated by the OCBench MJWarp scripted expert with the same
seeding as the streaming pipeline (generate_mjwarp_datasets(..., root_seed=data_seed, collection_idx=i)),
so a fixed-N dataset is collections 0..N/1000-1 and replay/refresh runs draw later indices.
Only successful episodes are kept (as in train.py); qpos is kept as float16 for later re-rendering.

  data/collections/<env>-d<seed>/c00012.npz   train collection 12
  data/collections/<env>-d<seed>/val.npz      128 held-out episodes (collection index 0, val split)

CLI (GPU, JAX venv):  python scripts/collections_store.py --idx 0-9 --val
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
KEYS = ('observations', 'observation_interval', 'actions', 'rewards', 'masks', 'terminals', 'qpos')
STORE = ROOT / 'data' / 'collections'


def store_dir(env, seed):
    return STORE / f'{env}-d{seed}'


def path(env, seed, idx, root=None):
    return (Path(root) if root else store_dir(env, seed)) / (f'c{idx:05d}.npz' if idx != 'val' else 'val.npz')


def generate(env, seed, idx, out, episodes=1000, val_episodes=0):
    """Generate one collection and save it atomically; returns collection metrics."""
    sys.path.insert(0, str(ROOT / 'ocbench' / 'impls'))
    from envs.streaming_data import generate_mjwarp_datasets
    from utils.datasets import filter_success_trajectories
    sys.path.insert(0, str(ROOT / 'scripts'))
    from simulation import configure_iteration_warnings
    configure_iteration_warnings(False)
    t0 = time.time()
    is_val = idx == 'val'
    train, val, metrics = generate_mjwarp_datasets(env, episodes if not is_val else 1, val_episodes if is_val else 0,
                                                   seed, 0 if is_val else idx, max_parallel_episodes=1000)
    raw = val if is_val else train
    raw = {k: v for k, v in raw.items() if k in KEYS}
    n_all = int(raw['terminals'].sum())
    raw = filter_success_trajectories(raw)
    raw['qpos'] = raw['qpos'].astype(np.float16)
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(out.name + f'.tmp{os.getpid()}.npz')
    np.savez(tmp, **raw)
    tmp.replace(out)
    rec = dict(idx=idx, episodes=n_all, successful=int(raw['terminals'].sum()),
               success_rate=int(raw['terminals'].sum()) / max(n_all, 1),
               transitions=int(len(raw['actions'])), seconds=round(time.time() - t0, 1),
               **{k: float(v) for k, v in metrics.items() if isinstance(v, (int, float, np.floating))})
    print(json.dumps(rec), flush=True)
    with open(out.parent / 'generation.jsonl', 'a') as f:
        f.write(json.dumps(rec) + '\n')
    return rec


def ensure(env, seed, idx, root=None):
    p = path(env, seed, idx, root)
    if not p.exists():
        generate(env, seed, idx, p, val_episodes=128)
    return p


def load(paths):
    """Concatenate whole-episode collections into one raw dict (train.py format plus qpos)."""
    parts = []
    for p in paths:
        with np.load(p) as d:
            parts.append({k: d[k] for k in d.files})
    return load_parts(parts)


def load_parts(parts, keep=False):
    """Concatenate raw dicts; unless keep, frees each part's arrays as they are consumed."""
    if len(parts) == 1:
        return dict(parts[0])
    out = {}
    for k in list(parts[0]):
        out[k] = parts[0][k] if k == 'observation_interval' else np.concatenate([q[k] for q in parts])
        if not keep:
            for q in parts:
                q[k] = None
    return out


def parse_range(s):
    out = []
    for part in s.split(','):
        a, _, b = part.partition('-')
        out.extend(range(int(a), int(b or a) + 1))
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--env', default='block-double-task1-v0')
    p.add_argument('--seed', type=int, default=0)
    p.add_argument('--idx', default='')
    p.add_argument('--val', action='store_true')
    p.add_argument('--out-dir', help='write here instead of the shared store (ephemeral refresh data)')
    args = p.parse_args()
    if args.val:
        ensure(args.env, args.seed, 'val', args.out_dir)
    for i in parse_range(args.idx) if args.idx else []:
        ensure(args.env, args.seed, i, args.out_dir)
    print('DONE', flush=True)


if __name__ == '__main__':
    main()
